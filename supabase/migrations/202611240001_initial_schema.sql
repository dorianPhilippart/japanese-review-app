-- Kanji Sprint cloud schema. Browser clients must use a publishable key only.

create table if not exists public.vocabulary (
  id bigint generated by default as identity primary key,
  kanji text not null,
  word text not null unique,
  reading text not null,
  romaji text not null,
  meaning_fr text not null,
  clue_fr text,
  jlpt_level text not null check (jlpt_level in ('N5', 'N4', 'N3', 'N2', 'N1')),
  tags text[] not null default '{}',
  example_jp text,
  example_reading text,
  example_fr text,
  audio_url text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists vocabulary_level_active_idx on public.vocabulary (jlpt_level, active);

create table if not exists public.user_preferences (
  user_id uuid primary key references auth.users (id) on delete cascade default auth.uid(),
  level text not null default 'all' check (level in ('all', 'N5', 'N4', 'N3', 'N2', 'N1')),
  session_length integer not null default 5 check (session_length between 5 and 100),
  daily_goal integer not null default 10 check (daily_goal between 1 and 500),
  updated_at timestamptz not null default now()
);

create table if not exists public.user_progress (
  user_id uuid not null references auth.users (id) on delete cascade default auth.uid(),
  vocabulary_id bigint not null references public.vocabulary (id) on delete cascade,
  seen integer not null default 0 check (seen >= 0),
  correct integer not null default 0 check (correct >= 0 and correct <= seen),
  ease_factor numeric(4,2) not null default 2.50 check (ease_factor between 1.30 and 3.50),
  interval_days integer not null default 0 check (interval_days between 0 and 3650),
  due_at timestamptz not null default now(),
  last_reviewed_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (user_id, vocabulary_id)
);

create index if not exists user_progress_user_due_idx on public.user_progress (user_id, due_at);
create index if not exists user_progress_vocabulary_idx on public.user_progress (vocabulary_id);

create table if not exists public.review_events (
  id bigint generated always as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade default auth.uid(),
  vocabulary_id bigint not null references public.vocabulary (id) on delete cascade,
  result boolean not null,
  mode text not null check (mode in ('recognition', 'typing', 'mcq', 'quick', 'weak')),
  reviewed_at timestamptz not null default now()
);

create index if not exists review_events_user_date_idx on public.review_events (user_id, reviewed_at desc);

create or replace function public.set_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists vocabulary_set_updated_at on public.vocabulary;
